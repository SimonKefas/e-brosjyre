import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import { writeFile } from 'node:fs/promises';
const hex = value => rgb(...value.match(/\w\w/g).map(v => parseInt(v, 16) / 255));
const C = { paper: hex('f1ecdf'), green: hex('283d31'), orange: hex('bc5535'), pale: hex('d3d5ab'), ink: hex('293c30') };
export async function generateDemo(path) {
  const doc = await PDFDocument.create();
  doc.setTitle('Smaken av sesongen — en eksempelbrosjyre');
  doc.setAuthor('E-brosjyre');
  const serif = await doc.embedFont(StandardFonts.TimesRoman);
  const italic = await doc.embedFont(StandardFonts.TimesRomanItalic);
  const sans = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const page = (background = C.paper) => {
    const p = doc.addPage([420, 594]);
    p.drawRectangle({ width:420, height:594, color:background });
    return p;
  };
  const text = (p, value, x, y, size=12, font=sans, color=C.ink) => p.drawText(value, { x, y, size, font, color, lineHeight:size*1.35 });
  const line = (p, y, color=C.ink) => p.drawLine({ start:{x:30,y}, end:{x:390,y}, thickness:.5, color, opacity:.35 });
  const footer = (p, n) => { line(p, 34); text(p, 'SESONG  /  EN EKSEMPELBROSJYRE', 30, 20, 7); text(p, String(n).padStart(2, '0'), 376, 20, 8); };
  const fruit = (p,x,y,r) => {
    p.drawCircle({ x,y,size:r,color:C.orange });
    p.drawCircle({ x:x+4,y:y+3,size:r*.75,color:hex('d87943') });
    p.drawLine({start:{x:x-3,y:y+r-2},end:{x:x+7,y:y+r+18},thickness:3,color:C.green});
    p.drawEllipse({x:x+17,y:y+r+8,xScale:15,yScale:5,rotate:{type:'degrees',angle:25},color:C.green});
  };
  let p = page(C.green);
  text(p,'S E S O N G',30,550,11,bold,C.paper);
  text(p,'MATGLEDE, HELE ÅRET',270,551,7,sans,C.pale);
  p.drawLine({start:{x:30,y:533},end:{x:390,y:533},thickness:.5,color:C.paper,opacity:.4});
  text(p,'Smaken av',30,458,51,serif,C.paper);
  text(p,'sesongen.',30,405,57,italic,C.pale);
  text(p,'Gode råvarer. Små øyeblikk. Store smaker.',33,371,10,sans,C.paper);
  p.drawRectangle({x:30,y:68,width:360,height:273,color:C.pale});
  p.drawEllipse({x:213,y:105,xScale:142,yScale:15,color:hex('b4b98e')});
  p.drawRectangle({x:199,y:123,width:64,height:151,color:C.green});
  p.drawEllipse({x:231,y:270,xScale:32,yScale:20,color:C.green});
  p.drawRectangle({x:219,y:270,width:24,height:49,color:C.green});
  p.drawRectangle({x:217,y:310,width:28,height:17,color:hex('aa8051')});
  p.drawRectangle({x:201,y:169,width:60,height:70,color:C.paper});
  text(p,'S E S O N G',207,220,6,bold); text(p,'Eple',207,196,20,italic); text(p,'REN FRUKT',212,182,5,sans);
  fruit(p,136,132,45); fruit(p,293,125,32);
  text(p,'EN LITEN SAMLING INSPIRASJON',30,39,7,sans,C.paper);
  text(p,'01 / 2026',333,39,8,sans,C.paper);
  p=page();
  text(p,'01  /  VELKOMMEN TIL BORDET',30,550,8,bold);
  text(p,'Det gode ligger\ni det enkle.',30,473,42,serif);
  text(p,'Et måltid trenger ikke være stort for å bli husket.\nNoen gode råvarer, noe godt i glasset og tid\ntil å være sammen. Det er nok.',32,353,12,sans);
  p.drawRectangle({x:30,y:101,width:360,height:200,color:C.orange});
  text(p,'Mer tid rundt\nbordet.',51,237,38,italic,C.paper);
  text(p,'MINDRE HAST. MER SMAK.',53,133,8,bold,C.paper); footer(p,2);
  p=page();
  text(p,'02  /  SESONGENS UTVALG',30,550,8,bold);
  text(p,'Fra naturen,\ntil deg.',30,487,39,serif);
  const products=[['01','Eple & ingefær','Frisk frukt med en varm avslutning.'],['02','Blodappelsin','Fyldig sitrus med et lite hint av bitterhet.'],['03','Pære & hylleblomst','Myk, floral og laget for lange måltider.']];
  products.forEach(([n,title,description],i)=>{const y=340-i*111; p.drawCircle({x:70,y:y+12,size:32,color:i===1?C.orange:C.pale});text(p,n,58,y+4,23,italic,i===1?C.paper:C.green);text(p,title,120,y+23,22,serif);text(p,description,120,y+2,8,sans);text(p,'SERVERES AVKJØLT  /  0,75 L',120,y-18,6,bold);if(i<2)line(p,y-44);});footer(p,3);
  p=page(C.pale);
  text(p,'03  /  ET LITE SERVERINGSTIPS',30,550,8,bold);
  fruit(p,207,341,108);
  text(p,'Litt syrlig.\nHelt nydelig.',30,155,43,italic);
  text(p,'Sitrus, is og et øyeblikk for deg selv.',33,78,11);footer(p,4);
  p=page();
  text(p,'04  /  OPPSKRIFT',30,550,8,bold);
  text(p,'Et glass\nsolskinn.',30,471,48,serif);
  text(p,'ENKELT Å LAGE  /  2 GLASS',32,367,8,bold);
  const rows=[['2 dl','Eplemost'],['1 dl','Kullsyrevann'],['½','Appelsin'],['Et par','Isbiter og friske urter']];
  rows.forEach(([amount,ingredient],i)=>{text(p,amount,32,319-i*38,12,bold);text(p,ingredient,107,319-i*38,12);line(p,305-i*38);});
  text(p,'Fyll to glass med is. Fordel eplemost og\nkullsyrevann. Topp med appelsin og urter.\nServer med noe godt å dele.',32,126,12);footer(p,5);
  p=page(C.green);
  text(p,'S E S O N G',30,550,11,bold,C.paper);
  text(p,'De beste\nøyeblikkene\ndeler vi.',30,395,49,italic,C.paper);
  text(p,'Takk for at du bladde innom.',33,184,12,sans,C.pale);
  text(p,'Dette er en eksempel-PDF laget for e-brosjyre.\nBytt til din egen PDF for å fortelle din historie.',33,104,10,sans,C.paper);
  text(p,'SESONG  /  2026',30,35,8,sans,C.paper);
  await writeFile(path, await doc.save());
}
